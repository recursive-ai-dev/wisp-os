/// Look up the 16-byte row bitmap for a printable ASCII character.
///
/// Any character outside the embedded 0x20-0x7E range (including control
/// characters that the shell handles separately, like backspace or enter)
/// falls back to a blank glyph rather than panicking, so unexpected input
/// never corrupts the display or crashes the shell.
#[must_use]
